"""Generated sources: stock.h, veneers into stock, entry stubs, C dispatchers, the linker script."""
from __future__ import annotations

import re
from pathlib import Path

from capstone import CS_ARCH_ARM, CS_MODE_MCLASS, CS_MODE_THUMB, Cs

from .errors import BuildError
from .features import Version, handlers
from .lock import Lock
from .memory import Region
from .symbols import Symbols

HEAD_C = "/* Generated by playbuild. Do not edit. */\n"
HEAD_S = "@ Generated by playbuild. Do not edit.\n    .syntax unified\n    .cpu cortex-m7\n    .thumb\n"


def split_decl(decl: str) -> tuple[str, str]:
    m = re.fullmatch(r"\s*(.*?[\s*])(\w+)\s*", decl)
    if not m:
        raise BuildError(f"cannot split C declaration {decl!r} into type and name")
    return m.group(1).strip(), m.group(2)


def stock_h(sym: Symbols) -> str:
    out = [HEAD_C, "#pragma once\n#include <stdint.h>\n\n/* Stock functions, called through veneers (stock_veneers.S). */\n"]
    for f in sorted(sym.functions.values(), key=lambda f: f.addr):
        if f.proto:
            out.append(f"{f.proto}; /* 0x{f.addr:08X} */\n")
        else:
            out.append(f"/* {f.name} 0x{f.addr:08X}: no prototype, not callable from C; tags: {', '.join(sorted(f.tags))} */\n")
    out.append("\n/* Stock data, addresses set in slim.ld. */\n")
    for d in sorted(sym.data.values(), key=lambda d: d.addr):
        decl = f"{d.ctype[:-2]} {d.name}[]" if d.ctype.endswith("[]") else f"{d.ctype} {d.name}"   # "T[]": an array
        out.append(f"extern volatile {decl}; /* 0x{d.addr:08X} */\n")
    return "".join(out)


def veneers_s(sym: Symbols) -> str:
    out = [HEAD_S]
    for f in sorted(sym.functions.values(), key=lambda f: f.name):
        if not f.proto:
            continue
        out.append(f"""
    .section .text.stock.{f.name},"ax",%progbits
    .global {f.name}
    .type {f.name}, %function
    .p2align 2
    .thumb_func
{f.name}:
    ldr.w pc, 1f
    .p2align 2
1:  .word {f.addr | 1:#010x}
""")
    return "".join(out)


def _displaced(expect: bytes, addr: int, n: int) -> str:
    md = Cs(CS_ARCH_ARM, CS_MODE_THUMB | CS_MODE_MCLASS)
    text = "; ".join(f"{i.mnemonic} {i.op_str}" for i in md.disasm(expect[:n], addr))
    halves = [int.from_bytes(expect[k:k + 2], "little") for k in range(0, n, 2)]
    return f"    @ displaced stock instructions: {text}\n" + "".join(f"    .inst.n {h:#06x}\n" for h in halves)


def entry_stubs_s(sym: Symbols, version: Version) -> str:
    out = [HEAD_S]
    for point in sorted(handlers(version)):
        hp = sym.hooks[point]
        if hp.kind == "mid":
            out.append(_mid_stub(point, hp))
            continue
        if hp.kind != "entry":
            continue
        # A void hook's caller ignores r0, so its stub keeps the bytes PL01 / SL00D were tested with.
        frame = ("    sub     sp, sp, #8\n" if hp.ret == "void" else
                 "    movs    r4, #0\n    strd    r4, r4, [sp, #-8]!     @ ret = 0: what stock gets if a handler leaves it\n")
        out.append(f"""
    .section .text.slim_entry_{point},"ax",%progbits
    .global slim_entry_{point}
    .type slim_entry_{point}, %function
    .p2align 2
    .thumb_func
slim_entry_{point}:
    push    {{r4, lr}}
{frame}    push    {{r0-r3}}              @ slim_args_t at sp: r[0..3], ret, pad
    mov     r0, sp
    bl      slim_dispatch_{point}
    cmp     r0, #0
    bne     1f
    pop     {{r0-r3}}              @ SLIM_PASS: restore the arguments, run stock
    add     sp, sp, #8
    pop     {{r4, lr}}
{_displaced(hp.expect, hp.addr, hp.displace)}    ldr.w   pc, 2f
1:  ldr     r0, [sp, #16]          @ SLIM_HANDLED: return the handler's result to stock's caller
    add     sp, sp, #24
    pop     {{r4, pc}}
    .p2align 2
2:  .word   {(hp.addr + hp.displace) | 1:#010x}
""")
    return "".join(out)


def _mid_stub(point: str, hp) -> str:
    """A mid hook (PL16): stock's displaced instructions first, then the handlers with every register in a slim_regs_t
    (r0-r12, lr, APSR, pad: 64 B, checks.MID_STUB_STACK), then stock goes on with the registers the handlers left."""
    return f"""
    .section .text.slim_entry_{point},"ax",%progbits
    .global slim_entry_{point}
    .type slim_entry_{point}, %function
    .p2align 2
    .thumb_func
slim_entry_{point}:
{_displaced(hp.expect, hp.addr, hp.displace)}    sub     sp, sp, #8             @ the flags and a pad word, above the registers
    push    {{r0-r12, lr}}         @ slim_regs_t at sp: r[0..12], lr, apsr, pad
    mrs     r0, APSR
    str     r0, [sp, #56]
    mov     r0, sp
    bl      slim_dispatch_{point}
    ldr     r0, [sp, #56]
    msr     APSR_nzcvqg, r0
    pop     {{r0-r12, lr}}         @ as the handlers left them
    add     sp, sp, #8
    ldr.w   pc, 2f
    .p2align 2
2:  .word   {(hp.addr + hp.displace) | 1:#010x}
"""


def dispatch_c(sym: Symbols, version: Version) -> str:
    uses = handlers(version)
    out = [HEAD_C, '#include "slim.h"\n#include "stock.h"\n\n/* Handlers */\n']
    for point in sorted(uses):
        hp = sym.hooks[point]
        params = ", ".join(hp.args) if hp.args else "void"
        for _, u in uses[point]:
            if hp.kind == "mid":
                out.append(f"void {u.handler}(slim_regs_t *regs);\n")
            elif hp.kind == "entry":
                extra = ", ".join(list(hp.args) + ["uint32_t *ret"])
                out.append(f"int {u.handler}({extra});\n")
            elif hp.ret == "void":
                out.append(f"void {u.handler}({params});\n")
            else:
                extra = ", ".join(list(hp.args) + ["uint32_t result"])
                rtype = hp.ret if u.filter else "void"
                out.append(f"{rtype} {u.handler}({extra});\n")
    for f in version.features:
        if f.init:
            out.append(f"void {f.init}(void);\n")
    out.append("\n/* Dispatchers */\n")
    for point in sorted(uses):
        hp = sym.hooks[point]
        names = [split_decl(a)[1] for a in hp.args]
        if hp.kind == "mid":
            out.append(f"\n/* mid hook {point} at 0x{hp.addr:08X}: after the displaced instructions; the handlers read "
                       "and change the registers */\n")
            out.append(f"void slim_dispatch_{point}(slim_regs_t *regs);\nvoid slim_dispatch_{point}(slim_regs_t *regs)\n{{\n")
            out.append("    if (!slim_ready())\n        return;\n")
            out += [f"    {u.handler}(regs);\n" for _, u in uses[point]]
            out.append("}\n")
        elif hp.kind == "entry":
            casts = ", ".join(f"({split_decl(a)[0]})a->r[{k}]" for k, a in enumerate(hp.args))
            call_args = ", ".join([c for c in [casts] if c] + ["&a->ret"])
            out.append(f"\n/* entry hook {point} at 0x{hp.addr:08X}: {hp.ret} ({', '.join(hp.args)}) */\n")
            out.append(f"int slim_dispatch_{point}(slim_args_t *a);\nint slim_dispatch_{point}(slim_args_t *a)\n{{\n")
            out.append("    if (!slim_ready())\n        return SLIM_PASS;\n")
            for _, u in uses[point]:
                out.append(f"    if ({u.handler}({call_args}) == SLIM_HANDLED)\n        return SLIM_HANDLED;\n")
            out.append("    return SLIM_PASS;\n}\n")
        else:
            params = ", ".join(hp.args) if hp.args else "void"
            args = ", ".join(names)
            sites = ", ".join(f"0x{s:08X}" for s in hp.sites)
            out.append(f"\n/* call hook {point} at {sites}: stock {hp.target}() first, then the handlers */\n")
            if hp.ret == "void":
                out.append(f"void slim_call_{point}({params});\nvoid slim_call_{point}({params})\n{{\n")
                out.append(f"    {hp.target}({args});\n    if (!slim_ready())\n        return;\n")
                for _, u in uses[point]:
                    out.append(f"    {u.handler}({args});\n")
                out.append("}\n")
            else:                                   # handlers see the result read-only; the call site gets it unchanged
                h_args = ", ".join(names + ["(uint32_t)result"])
                out.append(f"{hp.ret} slim_call_{point}({params});\n{hp.ret} slim_call_{point}({params})\n{{\n")
                out.append(f"    {hp.ret} result = {hp.target}({args});\n    if (!slim_ready())\n        return result;\n")
                for _, u in uses[point]:
                    if u.filter:
                        out.append(f"    result = ({hp.ret}){u.handler}({h_args});\n")
                    else:
                        out.append(f"    {u.handler}({h_args});\n")
                out.append("    return result;\n}\n")
    out.append("\nvoid slim_features_init(void)\n{\n")
    out += [f"    {f.init}();\n" for f in version.features if f.init]
    out.append("}\n")
    return "".join(out)


def linker_script(sym: Symbols, flash: Region, ram_origin: int, ram_length: int, ram_top: int,
                  itcm: tuple[int, int] | None = None) -> str:
    """itcm = (origin, length) when a feature asks for ITCM; None leaves the script exactly as before ITCM existed."""
    data = "".join(f"{d.name} = {d.addr:#010x};\n" for d in sorted(sym.data.values(), key=lambda d: d.addr))
    itcm_region = f"  ITCM (rw) : ORIGIN = {itcm[0]:#010x}, LENGTH = {itcm[1]:#x}\n" if itcm else ""
    itcm_section = ("""  .itcm (NOLOAD) :                              /* before .data / .bss: their *(.bss.*) would take it */
  {
    __slim_itcm_start = .;
    *(.bss.itcm.*)
    . = ALIGN(4);
    __slim_itcm_end = .;
  } > ITCM
""" if itcm else "")
    return f"""/* Generated by playbuild. Do not edit. */
ENTRY(slim_features_init)
MEMORY
{{
  FLASH (rx) : ORIGIN = {flash.start:#010x}, LENGTH = {flash.size:#x}
  RAM (rw) : ORIGIN = {ram_origin:#010x}, LENGTH = {ram_length:#x}
{itcm_region}}}
SECTIONS
{{
  .text :
  {{
    KEEP(*(.text.slim_entry_*))
    KEEP(*(.text.slim_call_*))
    *(.text .text.*)
    *(.glue_7 .glue_7t .vfp11_veneer .v4_bx)     /* linker-made veneers (empty in Thumb-only code) */
    *(.rodata .rodata.*)
    . = ALIGN(4);
  }} > FLASH
  .iplt : {{ *(.iplt .igot.plt .rel.iplt) }} > FLASH
  ASSERT(SIZEOF(.iplt) == 0, "slim code has no ifuncs: .iplt / .igot.plt / .rel.iplt must stay empty")
{itcm_section}  .data :
  {{
    __slim_data_start = .;
    *(.data .data.*)
    . = ALIGN(4);
    __slim_data_end = .;
  }} > RAM AT > FLASH
  __slim_data_load = LOADADDR(.data);
  .bss (NOLOAD) :
  {{
    __slim_bss_start = .;
    *(.bss .bss.* COMMON)
    . = ALIGN(4);
    __slim_bss_end = .;
  }} > RAM
  __slim_ram_start = ORIGIN(RAM);
  __slim_ram_end = __slim_bss_end;
  .comment 0 : {{ *(.comment) }}
  .ARM.attributes 0 : {{ *(.ARM.attributes) }}
  /DISCARD/ : {{ *(.ARM.exidx*) *(.ARM.extab*) *(.debug*) }}   /* .debug*: libgcc members carry DWARF */
}}
__slim_ram_top = {ram_top:#010x};
{data}"""


def write_linker_script(gen_dir: Path, sym: Symbols, flash: Region, ram_origin: int, ram_length: int,
                        ram_top: int, itcm: tuple[int, int] | None = None) -> Path:
    p = Path(gen_dir) / "slim.ld"
    p.write_text(linker_script(sym, flash, ram_origin, ram_length, ram_top, itcm))
    return p


SAVED_FEATURE = "saved"     # the feature that stores the saved fields (features/saved): the table is made for it


def _saved_fields(version: Version, lk: Lock) -> list[tuple]:
    """(lock entry, field) of the version's saved fields, in payload order."""
    declared = {f.symbol: f for feat in version.features for f in feat.saved}
    return [(e, declared[e.symbol]) for e in lk.entries if not e.tombstone and e.symbol in declared]


def saved_h(lk: Lock, n: int) -> str:
    return (HEAD_C + "#pragma once\n#include <stdint.h>\n\n/* The saved fields (save_layout.lock), for features/saved. */\n"
            f"#define SLIM_SAVED_LAYOUT {lk.layout_id}u\n#define SLIM_SAVED_LEN {lk.length}u   /* payload bytes */\n"
            f"#define SLIM_SAVED_N {n}u\n\n"
            "typedef struct {\n    uint8_t *addr;\n    uint8_t size, offset;   /* offset in the payload */\n"
            "    const uint8_t *def;     /* what a load without (valid) data gives it */\n} slim_saved_field_t;\n\n"
            "extern const slim_saved_field_t slim_saved_fields[SLIM_SAVED_N];\n"
            "void slim_saved_fix(void);   /* every feature's saved_fix, after a load wrote the fields (UI task) */\n")


def saved_c(version: Version, lk: Lock) -> str:
    fields = _saved_fields(version, lk)
    out = [HEAD_C, '#include "slim_saved.h"\n\n']
    out += [f"extern uint8_t {f.symbol}[];\n" for _, f in fields]
    out.append("\n")
    out += [f"static const uint8_t def_{f.symbol}[{f.size}] = {{{', '.join(f'0x{b:02X}' for b in f.default)}}};\n"
            for _, f in fields]
    out.append("\nconst slim_saved_field_t slim_saved_fields[SLIM_SAVED_N] = {\n")
    out += [f"    {{{f.symbol}, {e.size}u, {e.offset}u, def_{f.symbol}}},\n" for e, f in fields]
    out.append("};\n\n")
    fixes = [feat.saved_fix for feat in version.features if feat.saved_fix]
    out += [f"void {fn}(void);\n" for fn in fixes]
    out.append("\nvoid slim_saved_fix(void)\n{\n" + "".join(f"    {fn}();\n" for fn in fixes) + "}\n")
    return "".join(out)


LINK_FEATURE = "link"        # the CTCtrl link (features/link): slim_link.c is made for it


def _saved_offsets(version: Version, lk: Lock | None) -> list[tuple]:
    """(lock entry, field) of every saved field of the version, in payload order; none without a lock."""
    return _saved_fields(version, lk) if lk else []


def link_h(version: Version, lk: Lock | None) -> str:
    """Every version gets it: the payload offsets of its saved fields (features' link functions use them), and the
    linked field table's declarations when the version has the link."""
    out = [HEAD_C, "#pragma once\n#include <stdint.h>\n\n/* The saved fields' payload offsets and the CTCtrl link's "
           "field table (features/link). */\n"]
    out += [f"#define SLIM_OFF_{f.symbol} {e.offset}u\n" for e, f in _saved_offsets(version, lk)]
    if not any(f.name == LINK_FEATURE for f in version.features):
        return "".join(out) + "#define SLIM_LINK_N 0u\n"
    linked = [(e, f) for e, f in _saved_offsets(version, lk) if f.link]
    out.append(f"\n#define SLIM_LINK_N {len(linked)}u\n#define SLIM_LINK_MARKER \"{version.marker:<6}\"   "
               "/* the version marker, space-padded to 6 */\n\n"
               "typedef struct {\n    uint16_t offset;\n    uint8_t size, rev;\n} slim_link_field_t;\n\n"
               "extern const slim_link_field_t slim_link_fields[SLIM_LINK_N];   /* lock order, linked fields only */\n"
               "int slim_link_valid(const uint8_t *cand, const uint8_t *old);   /* every feature's link_valid */\n"
               "void slim_link_apply(const uint8_t *old);   /* every feature's link_apply, after a write (UI task) */\n")
    return "".join(out)


def link_c(version: Version, lk: Lock) -> str:
    linked = [(e, f) for e, f in _saved_offsets(version, lk) if f.link]
    out = [HEAD_C, '#include "slim_link.h"\n\nconst slim_link_field_t slim_link_fields[SLIM_LINK_N] = {\n']
    out += [f"    {{{e.offset}u, {e.size}u, {f.rev}u}},\n" for e, f in linked]
    out.append("};\n\n")
    valid = [feat.link_valid for feat in version.features if feat.link_valid]
    apply = [feat.link_apply for feat in version.features if feat.link_apply]
    out += [f"int {fn}(const uint8_t *cand, const uint8_t *old);\n" for fn in valid]
    out += [f"void {fn}(const uint8_t *old);\n" for fn in apply]
    out.append("\nint slim_link_valid(const uint8_t *cand, const uint8_t *old)\n{\n"
               + ("" if valid else "    (void)cand;\n    (void)old;\n")
               + "    return 1" + "".join(f" && {fn}(cand, old)" for fn in valid) + ";\n}\n")
    out.append("\nvoid slim_link_apply(const uint8_t *old)\n{\n" + ("" if apply else "    (void)old;\n")
               + "".join(f"    {fn}(old);\n" for fn in apply) + "}\n")
    return "".join(out)


def write_all(gen_dir: Path, sym: Symbols, version: Version, flash: Region, ram_origin: int, ram_length: int,
              ram_top: int, itcm: tuple[int, int] | None = None, lk: Lock | None = None) -> list[Path]:
    gen_dir = Path(gen_dir)
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "stock.h").write_text(stock_h(sym))
    sources = []
    for name, text in (("stock_veneers.S", veneers_s(sym)), ("hooks.S", entry_stubs_s(sym, version)),
                       ("dispatch.c", dispatch_c(sym, version))):
        (gen_dir / name).write_text(text)
        sources.append(gen_dir / name)
    if any(f.name == SAVED_FEATURE for f in version.features):          # only then: other builds keep their sources
        n = len(_saved_fields(version, lk))
        if not n:
            raise BuildError(f"{SAVED_FEATURE}: no feature of {version.name} declares [[saved]] fields")
        (gen_dir / "slim_saved.h").write_text(saved_h(lk, n))
        (gen_dir / "saved_fields.c").write_text(saved_c(version, lk))
        sources.append(gen_dir / "saved_fields.c")
    (gen_dir / "slim_link.h").write_text(link_h(version, lk))       # a header only: other builds keep their sources
    if any(f.name == LINK_FEATURE for f in version.features):
        (gen_dir / "link_fields.c").write_text(link_c(version, lk))
        sources.append(gen_dir / "link_fields.c")
    write_linker_script(gen_dir, sym, flash, ram_origin, ram_length, ram_top, itcm)
    return sources
